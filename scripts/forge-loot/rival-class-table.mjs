/**
 * Shadowdark Enhancer — derived Rival Crawler class table.
 *
 * The selector is deliberately a consumer of the G3 readiness report rather
 * than another readiness implementation.  G3 reports every candidate (and
 * therefore may contain both sides of a Core/importer collision); this module
 * applies the one source-selection policy the generated table owns:
 * Level-0 filtering, canonical-name deduplication with Core precedence, and
 * eligibility of the winning candidate.
 *
 * The payload builder is Foundry-free.  It produces a deterministic,
 * create-shaped RollTable payload; the Foundry adapter owns lookup and writes.
 */

import { MODULE_ID } from "../shared/module-id.mjs";
import { valueFingerprint } from "./forge-loot-core.mjs";

export const RIVAL_CLASS_TABLE_NAME = "Rival Crawler Classes";

/**
 * Where the generated table files inside the tables pack. The same path
 * resolveTableFolderPath gives the Core Rulebook's own Rival Crawler tables
 * (`Roll Tables > Core Rulebook > Rival Crawlers`), so the derived table sits
 * with the book tables it is rolled alongside instead of loose at the root —
 * which is where it landed, as the pack's only unfiled document.
 */
export const RIVAL_CLASS_TABLE_FOLDER = ["Roll Tables", "Core Rulebook", "Rival Crawlers"];
export const RIVAL_CLASS_TABLE_KEY = "forgeLoot.rivalClassTable";
export const RIVAL_CLASS_TABLE_VERSION = 1;

/** This text is also persisted in the generated table's description. */
export const RIVAL_CLASS_TABLE_WARNING =
  "Generated by Shadowdark Enhancer. Manual edits to rows or ranges are replaced on the next regeneration.";

function isObject(value) {
  return !!value && typeof value === "object";
}

function compareText(left, right) {
  const a = String(left ?? "");
  const b = String(right ?? "");
  return a < b ? -1 : a > b ? 1 : 0;
}

/** The canonical key shared with ClassIndex and the class-step Level-0 rule. */
export function canonicalClassName(name) {
  return String(name ?? "").trim().toLowerCase();
}

/** Reuse the exact Level-0 pseudo-class test used by class-step.mjs. */
export function isLevelZeroClassName(name) {
  return canonicalClassName(name).includes("level 0");
}

function sourceKey(source) {
  const value = String(source ?? "").trim().toLowerCase();
  if (value === "core" || value === "core rulebook" || value === "shadowdark core") return "core";
  if (value === "importer" || value === "importer-managed" || value === "managed"
    || value === "managed-classes" || value === "suite") return "importer-managed";
  return value;
}

function classIdentity(candidate) {
  return String(candidate?.classId ?? candidate?.uuid ?? candidate?.documentUuid
    ?? candidate?.id ?? candidate?._id ?? "").trim();
}

function candidateOrder(candidate) {
  return compareText(classIdentity(candidate), candidate?.name);
}

function reportClasses(report) {
  if (Array.isArray(report)) return report;
  if (isObject(report) && Array.isArray(report.classes)) return report.classes;
  // Do not consume report.eligible here.  It is intentionally pre-dedup in G3
  // and would allow an ineligible Core class to be silently shadowed.
  return [];
}

/**
 * Select the distinct classes that may appear in the derived table.
 *
 * Core precedence is applied before the winner's eligibility is inspected.
 * Thus an ineligible Core class excludes an eligible importer copy with the
 * same canonical name; there is no silent substitution across sources.
 *
 * @param {{classes?: Array<object>}|Array<object>} report G3 report
 * @returns {Array<object>} the winning, eligible class records
 */
export function selectRivalClasses(report = {}) {
  const groups = new Map();
  for (const candidate of reportClasses(report)) {
    if (!isObject(candidate)) continue;
    const name = String(candidate.name ?? "").trim();
    const key = canonicalClassName(name);
    const source = sourceKey(candidate.source);
    if (!key || isLevelZeroClassName(name)) continue;
    if (source !== "core" && source !== "importer-managed") continue;
    const normalized = { ...candidate, name };
    const current = groups.get(key);
    if (!current) {
      groups.set(key, normalized);
      continue;
    }
    const currentSource = sourceKey(current.source);
    // The G3 adapter already emits canonical source names.  Keep the source
    // as reported while using the normalized aliases only for precedence.
    if (source === "core" && currentSource !== "core") {
      groups.set(key, normalized);
    } else if (source === currentSource && candidateOrder(normalized) < candidateOrder(current)) {
      // A malformed source snapshot can contain two candidates from one pack;
      // still converge deterministically without inventing a second row.
      groups.set(key, normalized);
    }
  }

  return [...groups.entries()]
    .filter(([, candidate]) => candidate.eligible === true)
    .sort(([left], [right]) => compareText(left, right))
    .map(([, candidate]) => ({ ...candidate }));
}

export const selectEligibleRivalClasses = selectRivalClasses;

function resultType(value) {
  if (typeof value === "number") return value === 1 ? "document" : "text";
  const type = String(value ?? "").trim().toLowerCase();
  if (type === "document" || type === "doc") return "document";
  return "text";
}

function rowRange(row) {
  const range = Array.isArray(row?.range) ? row.range : [];
  const lo = Number(row?.lo ?? row?.min ?? range[0]);
  const hi = Number(row?.hi ?? row?.max ?? range[1] ?? row?.lo ?? row?.min ?? range[0]);
  return Number.isInteger(lo) && Number.isInteger(hi) ? [lo, hi] : null;
}

function rowName(row) {
  return String(row?.name ?? row?.text ?? row?.description ?? "").trim();
}

function rowDocumentUuid(row) {
  return String(row?.documentUuid ?? row?.documentUUID ?? row?.documentId ?? "").trim() || null;
}

/**
 * Project a table onto fields authored by this generator.  Foundry adds row
 * ids and DataModel defaults; neither is content and neither belongs in the
 * manual-edit witness.
 */
export function rivalClassTableContent(data = {}) {
  const results = Array.isArray(data.results) ? data.results
    : Array.isArray(data.rows) ? data.rows : [];
  return {
    name: String(data.name ?? RIVAL_CLASS_TABLE_NAME).trim(),
    description: String(data.description ?? ""),
    formula: String(data.formula ?? "").trim(),
    results: results.map((row) => ({
      type: resultType(row?.type),
      name: rowName(row),
      documentUuid: rowDocumentUuid(row),
      range: rowRange(row),
      weight: row?.weight == null ? 1 : Number(row.weight),
    })),
  };
}

export function rivalClassTableFingerprint(data = {}) {
  return valueFingerprint(rivalClassTableContent(data));
}

function winnerIdentity(winner) {
  return classIdentity(winner) || null;
}

function normalizedWinners(winners) {
  const groups = new Map();
  for (const winner of Array.isArray(winners) ? winners : []) {
    if (!isObject(winner)) continue;
    const name = String(winner.name ?? "").trim();
    const key = canonicalClassName(name);
    if (!key || isLevelZeroClassName(name)) continue;
    const candidate = { ...winner, name };
    const current = groups.get(key);
    if (!current || (sourceKey(candidate.source) === "core" && sourceKey(current.source) !== "core")
      || (sourceKey(candidate.source) === sourceKey(current.source)
        && candidateOrder(candidate) < candidateOrder(current))) groups.set(key, candidate);
  }
  return [...groups.entries()]
    .sort(([left], [right]) => compareText(left, right))
    .map(([, winner]) => winner);
}

/**
 * Build the deterministic RollTable.create payload for selected winners.
 * N=0 intentionally uses a valid inert `1d1` formula while retaining zero
 * results; the readiness report, not a missing table, disables Rival rolling.
 *
 * @param {Array<object>} winners output of selectRivalClasses
 * @returns {object} create-shaped RollTable data
 */
export function buildRivalClassTablePayload(winners = []) {
  const selected = normalizedWinners(winners);
  const formula = selected.length ? `1d${selected.length}` : "1d1";
  const results = selected.map((winner, index) => {
    const documentUuid = winnerIdentity(winner);
    return {
      ...(documentUuid ? { type: "document", documentUuid } : { type: "text" }),
      name: winner.name,
      weight: 1,
      range: [index + 1, index + 1],
    };
  });
  const content = {
    name: RIVAL_CLASS_TABLE_NAME,
    description: RIVAL_CLASS_TABLE_WARNING,
    formula,
    results,
  };
  const fingerprint = rivalClassTableFingerprint(content);
  return {
    ...content,
    flags: {
      [MODULE_ID]: {
        forgeLoot: {
          rivalClassTable: {
            generated: true,
            version: RIVAL_CLASS_TABLE_VERSION,
            fingerprint,
          },
        },
      },
    },
  };
}

export const buildRivalClassTable = buildRivalClassTablePayload;

/** Read the stored generator marker without accepting name-based identity. */
export function rivalClassTableMarker(document) {
  const marker = document?.flags?.[MODULE_ID]?.forgeLoot?.rivalClassTable;
  if (marker === null || marker === undefined || marker === false) return null;
  if (marker === true) return { generated: true };
  return isObject(marker) ? marker : null;
}

export function isRivalClassTable(document) {
  return !!rivalClassTableMarker(document);
}

export const _internals = Object.freeze({ resultType, rowRange, rowName, rowDocumentUuid });
