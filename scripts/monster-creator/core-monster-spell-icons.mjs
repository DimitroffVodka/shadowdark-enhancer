function normalizeSourceLabel(value) {
  const source = String(value ?? "").toLocaleLowerCase().replace(/\s+/g, " ").trim();
  const short = source.match(/^cs\s*(\d+)$/);
  return short ? `cursed scroll ${short[1]}` : source;
}

export function resolveCoreMonsterSpellIcon(item, actor, icons = CORE_MONSTER_SPELL_ICONS) {
  const fallback = item?.img ?? "icons/svg/book.svg";
  if (actor?.sourcePack !== "shadowdark.monsters") return fallback;
  return icons[String(item?.name ?? "").trim()] ?? fallback;
}

export function resolveMonsterSpellIcon(item, actor, {
  coreIcons = CORE_MONSTER_SPELL_ICONS,
  sourceIcons = CURSED_SCROLL_MONSTER_SPELL_ICONS,
} = {}) {
  const coreIcon = resolveCoreMonsterSpellIcon(item, actor, coreIcons);
  if (actor?.sourcePack === "shadowdark.monsters") return coreIcon;

  const fallback = item?.img ?? "icons/svg/book.svg";
  const source = normalizeSourceLabel(actor?.sourceLabel);
  const spell = String(item?.name ?? "").toLocaleLowerCase().replace(/\s+/g, " ").trim();
  return sourceIcons[`${source}::${spell}`] ?? fallback;
}
